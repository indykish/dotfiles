#!/usr/bin/env bash
# evals/install/cases.sh — the behaviours the installer must exhibit.
#
# Sourced by run.sh, never executed. Every function named install_* is
# discovered and run automatically; read this file as the list of claims the
# milestone makes, one function per claim.

# The payload is the product boundary: the engine ships, the laptop does not.
# Anything added to the repository root is excluded until package.json says
# otherwise, so a new personal file cannot leak by default.
install_package_allowlist_excludes_personal_files() {
  local name="package allowlist ships the engine and no personal file"
  local paths; paths="$(packed_paths)"
  if [[ -z "$paths" ]]; then bad "$name" "npm pack produced no file list"; return; fi

  local leaked
  leaked="$(printf '%s\n' "$paths" | grep -E '^(\.zshrc|\.zshenv|\.claude/|\.codex/|\.config/|Library/|skills/|evals/|SOUL_LOG\.md|\.gitconfig|\.tmux\.conf|\.npmrc|docs/v1/|Makefile)' || true)"
  if [[ -n "$leaked" ]]; then
    bad "$name" "personal paths in payload: $(printf '%s' "$leaked" | tr '\n' ' ')"; return
  fi

  local required missing=""
  for required in "bin/orly" "orly/registry.json" "dispatch/lib.sh" "audits/ufs.sh" ".githooks/pre-commit"; do
    printf '%s\n' "$paths" | grep -qxF "$required" || missing+="$required "
  done
  if [[ -n "$missing" ]]; then bad "$name" "engine paths absent from payload: $missing"; return; fi

  # bin/ carries machine-provisioning helpers that must never reach a consumer.
  local extra_bin
  extra_bin="$(printf '%s\n' "$paths" | grep -E '^bin/' | grep -vxF 'bin/orly' || true)"
  if [[ -n "$extra_bin" ]]; then
    bad "$name" "non-product bin entries shipped: $(printf '%s' "$extra_bin" | tr '\n' ' ')"; return
  fi

  # Adversarial review: names this machine's own project layout (private
  # directory names, no secret) and buys nothing for a stranger's install —
  # kernel is already the fallback when nothing in it would have matched.
  if printf '%s\n' "$paths" | grep -qxF "orly/repositories.json"; then
    bad "$name" "orly/repositories.json ships the maintainer's own project registry"; return
  fi
  ok "$name"
}

# The fix for the above: RulesModel.load() must treat a missing
# repositories.json as "no repositories registered", not an install failure —
# it is the normal state for everyone except this engine's own maintainer.
install_works_with_no_repositories_json_shipped() {
  local name="init works from a payload carrying no repositories.json"
  local pkg repo; pkg="$(packed_root)"; repo="$(mk_repo)"
  if [[ -z "$pkg" ]]; then bad "$name" "npm pack or extract failed"; return; fi
  if [[ -e "$pkg/orly/repositories.json" ]]; then bad "$name" "repositories.json is present — test premise broken"; return; fi

  local out; out="$(run_packed "$pkg" "$repo" init)"
  if [[ "$out" != *"written"* ]]; then bad "$name" "init did not materialise: $out"; return; fi
  ok "$name"
}

# The claim the whole milestone rests on: the published artifact works on a
# machine that has never seen this checkout. HOME is scratch and the working
# directory is outside the repository, so any surviving absolute path fails here.
install_packed_tarball_validates_standalone() {
  local name="packed tarball installs and renders with no dotfiles checkout"
  local pkg; pkg="$(packed_root)"
  if [[ -z "$pkg" || ! -x "$pkg/bin/orly" ]]; then bad "$name" "npm pack or extract failed"; return; fi

  local repo; repo="$(mk_repo)"
  local out; out="$(run_packed "$pkg" "$repo" init)"
  if [[ "$out" != *"written"* ]]; then
    bad "$name" "init failed from the tarball: $out"; return
  fi

  local sb; sb="$(mk_sandbox)"
  out="$(run_packed "$pkg" "$sb" render)"
  if [[ "$out" != *"Generated by"* ]]; then
    bad "$name" "render produced no rules from the tarball: ${out:0:120}"; return
  fi
  ok "$name"
}

# One version source. A second copy inside the sources would let an installed
# package report a version it is not.
install_version_comes_from_the_manifest() {
  local name="--version reports the packaged manifest version"
  local pkg; pkg="$(packed_root)"
  if [[ -z "$pkg" ]]; then bad "$name" "npm pack or extract failed"; return; fi

  local sb; sb="$(mk_sandbox)"
  local reported expected
  reported="$(run_packed "$pkg" "$sb" --version | tr -d '[:space:]')"
  expected="$(grep -m1 '"version"' "$pkg/package.json" | sed -E 's/.*: *"//; s/".*//')"
  if [[ -z "$expected" ]]; then bad "$name" "packed manifest carries no version"; return; fi
  if [[ "$reported" != "$expected" ]]; then
    bad "$name" "reported '$reported', manifest says '$expected'"; return
  fi
  ok "$name"
}

# The shim runs TypeScript through Bun. Without Bun the exec would surface as a
# bare "command not found"; a user who cannot act on the error is a failed
# install, so the guard must name the runtime and a way to get it.
install_missing_bun_names_the_fix() {
  local name="missing bun fails with a message naming the runtime and a fix"
  local pkg; pkg="$(packed_root)"
  if [[ -z "$pkg" ]]; then bad "$name" "npm pack or extract failed"; return; fi

  local sb; sb="$(mk_sandbox)"
  mkdir -p "$sb/emptybin"
  local out code
  out="$(cd "$sb" && env -i PATH="$sb/emptybin:/usr/bin:/bin" HOME="$sb/home" \
        bash "$pkg/bin/orly" validate 2>&1)"; code=$?
  if [[ "$code" -eq 0 ]]; then bad "$name" "expected failure without bun, got exit 0"; return; fi
  if [[ "$out" != *"bun is required"* ]]; then
    bad "$name" "error does not name the runtime: $out"; return
  fi
  if [[ "$out" != *"mise"* && "$out" != *"bun.sh"* ]]; then
    bad "$name" "error names no way to install it: $out"; return
  fi
  ok "$name"
}

# The core claim: a repository that has never seen this checkout ends up with
# rules, gates, hooks, and a lock, from one command run out of the package.
install_materialises_a_fresh_repository() {
  local name="init materialises rules, gates, hooks, and a lock into a fresh repository"
  local pkg repo; pkg="$(packed_root)"; repo="$(mk_repo)"
  if [[ -z "$pkg" ]]; then bad "$name" "npm pack or extract failed"; return; fi

  local out; out="$(run_packed "$pkg" "$repo" init)"
  if [[ "$out" != *"written"* ]]; then bad "$name" "init did not report success: $out"; return; fi

  local required missing=""
  for required in "AGENTS.md" ".oracle/orly.json" "dispatch/write_rust.md" "audits/ufs.sh" ".githooks/pre-commit"; do
    [[ -f "$repo/$required" ]] || missing+="$required "
  done
  if [[ -n "$missing" ]]; then bad "$name" "not materialised: $missing"; return; fi

  # AGENTS.md must be the generated render, not a copy of this repository's.
  grep -q "Generated by" "$repo/AGENTS.md" || { bad "$name" "AGENTS.md is not a render"; return; }
  ok "$name"
}

# Running twice must not churn the tree: a second install reports everything
# current and rewrites nothing, so `orly init` is safe to re-run in any state.
install_is_idempotent() {
  local name="a second init writes nothing and leaves the tree byte-identical"
  local pkg repo; pkg="$(packed_root)"; repo="$(mk_repo)"
  if [[ -z "$pkg" ]]; then bad "$name" "npm pack or extract failed"; return; fi

  run_packed "$pkg" "$repo" init >/dev/null
  local before after out
  before="$(cd "$repo" && find . -path ./.git -prune -o -type f -print0 | sort -z | xargs -0 shasum | shasum)"
  out="$(run_packed "$pkg" "$repo" init)"
  after="$(cd "$repo" && find . -path ./.git -prune -o -type f -print0 | sort -z | xargs -0 shasum | shasum)"

  if [[ "$before" != "$after" ]]; then bad "$name" "tree changed on the second run"; return; fi
  if [[ "$out" != *"0 written"* ]]; then bad "$name" "second run reported writes: $out"; return; fi
  ok "$name"
}

# A repository receives its own packs and nothing else. A Rust crate holding a Zig
# or UI gate is the defect this milestone found already shipped.
install_materialises_selected_packs_only() {
  local name="a Rust repository receives no Zig façade and no foreign gate"
  local pkg repo; pkg="$(packed_root)"; repo="$(mk_repo)"
  if [[ -z "$pkg" ]]; then bad "$name" "npm pack or extract failed"; return; fi

  run_packed "$pkg" "$repo" init >/dev/null
  [[ -f "$repo/dispatch/write_rust.md" ]] || { bad "$name" "the Rust façade was not installed"; return; }
  local path foreign=""
  for path in "dispatch/write_zig.md" "dispatch/write_ts_adhere_bun.md" "audits/design-tokens.sh" "audits/deinit-pairs.sh"; do
    [[ -e "$repo/$path" ]] && foreign+="$path "
  done
  if [[ -n "$foreign" ]]; then bad "$name" "foreign pack files installed: $foreign"; return; fi

  # Every dispatch path the installed rules cite must itself be installed.
  local cited dangling=""
  while read -r cited; do
    [[ -z "$cited" ]] && continue
    [[ -e "$repo/$cited" ]] || dangling+="$cited "
  done < <(cited_dispatch_paths "$repo")
  if [[ -n "$dangling" ]]; then bad "$name" "installed rules cite absent façades: $dangling"; return; fi
  ok "$name"
}

# Hooks are what make the gates fire without anyone remembering to run them,
# and they must carry the git-scope scrub or they judge the wrong repository.
install_installs_scoped_hooks() {
  local name="init sets core.hooksPath and the hooks scrub inherited git scope"
  local pkg repo; pkg="$(packed_root)"; repo="$(mk_repo)"
  if [[ -z "$pkg" ]]; then bad "$name" "npm pack or extract failed"; return; fi

  run_packed "$pkg" "$repo" init >/dev/null
  local configured; configured="$(git -C "$repo" config --get core.hooksPath || true)"
  if [[ "$configured" != ".githooks" ]]; then bad "$name" "core.hooksPath is '$configured'"; return; fi

  local hook
  for hook in pre-commit pre-push; do
    [[ -x "$repo/.githooks/$hook" ]] || { bad "$name" "$hook is not executable"; return; }
    grep -q "GIT_DIR" "$repo/.githooks/$hook" || { bad "$name" "$hook does not unset GIT_DIR"; return; }
  done
  ok "$name"
}

# Drift is the failure that actually happened: a vendored ruleset edited or
# rotted in place with nothing reporting it. doctor must see it, init must
# refuse it, and --force must be the only way through.
install_doctor_reports_drift_and_init_refuses() {
  local name="a hand edit is replaced by update; a file orly never wrote is refused"
  local pkg repo; pkg="$(packed_root)"; repo="$(mk_repo)"
  if [[ -z "$pkg" ]]; then bad "$name" "npm pack or extract failed"; return; fi

  run_packed "$pkg" "$repo" init >/dev/null
  printf '\n# tampered\n' >> "$repo/dispatch/write_rust.md"

  # An edit to a file orly wrote is not drift: this is a git repository, so the
  # edit and its replacement both show in `git diff` before either is committed.
  local out; out="$(run_packed "$pkg" "$repo" doctor)"
  if [[ "$out" == *"missing"* ]]; then bad "$name" "doctor called an edit a missing file: $out"; return; fi

  out="$(run_packed "$pkg" "$repo" update)"
  if [[ "$out" != *"written"* ]]; then bad "$name" "update did not re-materialise: $out"; return; fi
  if grep -q "tampered" "$repo/dispatch/write_rust.md"; then bad "$name" "update left the hand edit in place"; return; fi

  # Deleting one IS drift — only orly can restore what only orly wrote.
  rm "$repo/dispatch/write_rust.md"
  out="$(run_packed "$pkg" "$repo" doctor)"
  if [[ "$out" != *"missing"* ]]; then bad "$name" "doctor missed a deleted managed file: $out"; return; fi

  # A file orly never wrote belongs to the repository and is never replaced.
  local sb; sb="$(mk_repo)"
  printf 'the repository own file\n' > "$sb/AGENTS.md"
  out="$(run_packed "$pkg" "$sb" init)"
  if [[ "$out" != *"orly did not write it"* ]]; then bad "$name" "init did not refuse a foreign file: $out"; return; fi
  if ! grep -q "the repository own file" "$sb/AGENTS.md"; then bad "$name" "refusal still overwrote a foreign file"; return; fi
  ok "$name"
}


# A missing managed file is drift too — deletion must not read as "clean".
install_doctor_reports_drift_on_deletion() {
  local name="a deleted managed file is reported, not silently ignored"
  local pkg repo; pkg="$(packed_root)"; repo="$(mk_repo)"
  if [[ -z "$pkg" ]]; then bad "$name" "npm pack or extract failed"; return; fi

  run_packed "$pkg" "$repo" init >/dev/null
  rm -f "$repo/audits/ufs.sh"
  local out; out="$(run_packed "$pkg" "$repo" doctor)"
  if [[ "$out" != *"missing"* ]]; then bad "$name" "doctor did not report the deletion: $out"; return; fi
  ok "$name"
}

# update re-materialises what the lock already pinned, so a rule change costs
# one command. Without a lock there is nothing to update and it must say so.
install_update_requires_a_prior_install() {
  local name="update refuses in a repository that was never installed into"
  local pkg repo; pkg="$(packed_root)"; repo="$(mk_repo)"
  if [[ -z "$pkg" ]]; then bad "$name" "npm pack or extract failed"; return; fi

  local out; out="$(run_packed "$pkg" "$repo" update)"
  if [[ "$out" != *"orly init"* ]]; then bad "$name" "update did not name init as the fix: $out"; return; fi

  run_packed "$pkg" "$repo" init >/dev/null
  out="$(run_packed "$pkg" "$repo" update)"
  if [[ "$out" != *"already current"* ]]; then bad "$name" "update did not re-materialise: $out"; return; fi
  ok "$name"
}

# The structured surface is a contract other tools read; the human surface must
# not leak into it, and vice versa.
install_json_contract_is_separate_from_the_human_surface() {
  local name="--json emits the documented object and the human path emits none"
  local pkg repo; pkg="$(packed_root)"; repo="$(mk_repo)"
  if [[ -z "$pkg" ]]; then bad "$name" "npm pack or extract failed"; return; fi

  local out; out="$(run_packed "$pkg" "$repo" init --json)"
  local key missing=""
  for key in '"ok"' '"packs"' '"written"' '"skipped"' '"errors"'; do
    [[ "$out" == *"$key"* ]] || missing+="$key "
  done
  if [[ -n "$missing" ]]; then bad "$name" "json output lacks: $missing"; return; fi
  if ! printf '%s' "$out" | python3 -c 'import json,sys; json.load(sys.stdin)' 2>/dev/null; then
    bad "$name" "json output does not parse"; return
  fi

  local repo2; repo2="$(mk_repo)"
  out="$(run_packed "$pkg" "$repo2" init)"
  if [[ "$out" == *'"written"'* ]]; then bad "$name" "human path leaked json"; return; fi
  ok "$name"
}

